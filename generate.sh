#!/usr/bin/env bash
set -euo pipefail

here="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
out="$here/lua/ddlc/palette.lua"
syntax_out="$here/lua/ddlc/syntax.lua"

usage() {
  cat <<EOF
generate.sh — render the palette and syntax tables out of the base16 schemes and the
shared DDLC syntax table

It writes lua/ddlc/palette.lua and lua/ddlc/syntax.lua, the only generated files here.
The group tables next to them are the theme's own design and are written by hand; only
the colours come from upstream

  --light FILE    base16-ddlc-light.yaml   (or \$DDLC_BASE16_LIGHT)
  --dark FILE     base16-ddlc-dark.yaml    (or \$DDLC_BASE16_DARK)
  --syntax FILE   ddlc-syntax.json         (or \$DDLC_SYNTAX)

The schemes come from ddlc-palette and the syntax table from ddlc-themes, and nix develop
puts all three in the environment already. Without Nix, take them from the repositories:

  curl -sSLO https://raw.githubusercontent.com/rokokol/ddlc-palette/master/dist/base16-ddlc-dark.yaml
  curl -sSLO https://raw.githubusercontent.com/rokokol/ddlc-themes/master/dist/ddlc-syntax.json
EOF
}

declare -A scheme=(
  [light]="${DDLC_BASE16_LIGHT:-}"
  [dark]="${DDLC_BASE16_DARK:-}"
)
syntax="${DDLC_SYNTAX:-}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --light)
      scheme[light]="${2:?file required}"
      shift 2
      ;;
    --dark)
      scheme[dark]="${2:?file required}"
      shift 2
      ;;
    --syntax)
      syntax="${2:?file required}"
      shift 2
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      usage >&2
      exit 1
      ;;
  esac
done

slots() { sed -n 's/^  \(base[0-9A-F][0-9A-F]\): "\(#[0-9A-F]\{6\}\)".*/\1 \2/p' "$1"; }

for variant in light dark; do
  file="${scheme[$variant]}"
  [ -n "$file" ] || {
    echo "generate.sh: no $variant scheme — pass --$variant or set DDLC_BASE16_${variant^^}" >&2
    exit 1
  }
  # Sixteen slots or it is not a base16 scheme, and a half-read file would render a half-theme
  n=$(slots "$file" | wc -l)
  [ "$n" = 16 ] || {
    echo "generate.sh: $file has $n slots, want 16" >&2
    exit 1
  }
done

{
  echo "-- Generated by generate.sh from ddlc-palette's base16 schemes — do not edit"
  echo "return {"
  for variant in dark light; do
    echo "  $variant = {"
    slots "${scheme[$variant]}" | while read -r key hex; do echo "    $key = \"$hex\","; done
    echo "  },"
  done
  echo "}"
} >"$out"

# The syntax table's JSON is one "role": "#HEX" per line under "dark" and "light", as jq
# prints it. Both variants must name the same roles, or a group would read nil on one side
[ -n "$syntax" ] || {
  echo "generate.sh: no syntax table — pass --syntax or set DDLC_SYNTAX" >&2
  exit 1
}
roles() { # <variant>
  awk -v want="\"$1\": {" '
    index($0, want) { on = 1; next }
    on && /}/ { on = 0 }
    on && match($0, /"[a-z-]+": "#[0-9A-F]{6}"/) {
      split(substr($0, RSTART, RLENGTH), kv, "\"")
      print kv[2], kv[4]
    }' "$syntax"
}
dark_roles=$(roles dark | cut -d' ' -f1)
[ -n "$dark_roles" ] && [ "$dark_roles" = "$(roles light | cut -d' ' -f1)" ] || {
  echo "generate.sh: $syntax does not name the same roles for dark and light" >&2
  exit 1
}

{
  echo "-- Generated by generate.sh from ddlc-themes' syntax table — do not edit"
  echo "return {"
  for variant in dark light; do
    echo "  $variant = {"
    roles "$variant" | while read -r key hex; do echo "    [\"$key\"] = \"$hex\","; done
    echo "  },"
  done
  echo "}"
} >"$syntax_out"

echo "wrote $out and $syntax_out"
